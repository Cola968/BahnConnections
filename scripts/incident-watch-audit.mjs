import assert from "node:assert/strict";
import {parseIncidentWatches,toggleIncidentWatch,readIncidentWatch,filterWatchedIncidents} from "../app/incident-watch.ts";
const invalid=JSON.parse('{"__proto__":["EVIL"],"x":["S7","S7","","ICE 4",52],"other":"no","constructor":["S8"]}');
const clean=parseIncidentWatches(invalid);
assert.equal(Object.getPrototypeOf(clean),null,"No prototype pollution from stored preferences");
assert.deepEqual(Object.keys(clean),["x"]);
assert.deepEqual(readIncidentWatch(clean,"x"),["S7","ICE 4"]);
assert.deepEqual(readIncidentWatch(clean,"__proto__"),[]);
let w=toggleIncidentWatch(clean,"x","S1");
assert.deepEqual(w.x,["S7","ICE 4","S1"]);
assert.deepEqual(toggleIncidentWatch(w,"x","S1").x,["S7","ICE 4"]);
assert.equal(w.x.length,3,"Mutators must not change an earlier watchlist");
w=toggleIncidentWatch(w,"berlin","RE1");
assert.deepEqual(w.berlin,["RE1"]);
assert.deepEqual(filterWatchedIncidents([{lines:["RE1"]},{lines:["S7"]},{lines:[]}],["RE1"]).map(x=>x.lines),[["RE1"],[]],"Station-wide accessibility notices remain present");
assert.equal(filterWatchedIncidents([{lines:["S7"]}],[]).length,1,"No watch list means normal all-lines view");
assert.deepEqual(toggleIncidentWatch(w,"x","constructor"),parseIncidentWatches(w),"Unsafe pseudo keys cannot be bookmarked");
assert.equal(parseIncidentWatches(null).x,undefined);
let limit=parseIncidentWatches(Object.fromEntries(Array.from({length:30},(_,i)=>["station"+i,["S"+i]])));
assert.equal(Object.keys(limit).length,20,"Only 20 stations may be stored");
for(let i=0;i<20;i++)limit=toggleIncidentWatch(limit,"last-station","RE"+i);
assert.equal(readIncidentWatch(limit,"last-station").length,12,"Only 12 lines per station");
console.log("Station line watch audit passed");
