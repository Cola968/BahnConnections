import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { boardDisplayActual, boardDisplayPlatform, boardEventTime, boardPredictionFresh } from "../app/board-time.ts";
import { boardDedupeKey } from "../app/board-dedup.ts";
import { trainArrivalView } from "../app/train-arrival.ts";
import { deriveRealtimePresentation } from "../app/realtime-presentation.ts";

const schedule="2026-10-25T02:30:00+02:00";
const delayed="2026-10-25T02:40:00+02:00";
const board={plannedWhen:schedule,when:delayed,realtime:true,plannedPlatform:"4",platform:"7"};
assert.equal(boardDisplayActual(board,false),undefined,"Stale actual must be hidden");
assert.equal(boardEventTime(board,false),Date.parse(schedule),"Stale sort must use timetable");
assert.equal(boardDisplayPlatform(board,false),"4","Only planned platform is safe after expiry");
assert.equal(boardDisplayPlatform(board,true),"7","Fresh platform prediction is shown");
assert.equal(boardDisplayPlatform({realtime:true,platform:"7"},false),undefined);
assert.equal(boardPredictionFresh(new Date("2026-10-12T09:00:00Z"),Date.parse("2026-10-12T09:03:00Z"),false),false);
const stale=trainArrivalView({scheduled:schedule,actual:delayed,realtime:true,fresh:false});
assert.equal(stale.expected,null);
assert.equal(stale.delayMinutes,null);
assert.doesNotMatch(stale.status,/pünktlich/i);
const current=trainArrivalView({scheduled:schedule,actual:delayed,realtime:true,fresh:true});
assert.equal(current.delayMinutes,10);
assert.match(current.status,/Verspätung/);
const unknown=deriveRealtimePresentation({scheduled:schedule,realtime:true});
assert.equal(unknown.kind,"unknown");

const serviceA={kind:"departure",plannedWhen:schedule,plannedPlatform:"5",direction:"Potsdam",provenance:"Berlin",line:{name:"RE1",routeId:"re1",product:"regional"}};
const serviceB={...serviceA,line:{name:"RE7",routeId:"re7",product:"regional"}};
assert.notEqual(boardDedupeKey(serviceA),boardDedupeKey(serviceB),"Different lines at same time/platform cannot collapse");
assert.notEqual(boardDedupeKey(serviceA),boardDedupeKey({...serviceA,plannedWhen:delayed}),"Another departure minute is distinct");
assert.equal(boardDedupeKey({...serviceA,tripId:"trip-1"}),boardDedupeKey({...serviceB,tripId:"trip-1"}),"A stable tripId takes precedence");
const source=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const search=source("app/api/stations/search/route.ts");
assert.match(search,/query\.length > 100/);
assert.match(search,/AbortSignal\.timeout\(10_000\)/);
const trips=source("app/api/trips/[source]/[id]/route.ts");
assert.match(trips,/tripId\.length > 500/);
assert.match(trips,/AbortSignal\.timeout\(12_000\)/);
const boardApi=source("app/api/stations/[id]/board/route.ts");
assert.match(boardApi,/Ungültiger Abfragezeitpunkt/);
const services=source("app/api/stations/[id]/services/route.ts");
assert.match(services,/AbortSignal\.timeout\(12_000\)/);
assert.match(services,/Promise\.allSettled/);
assert.match(services,/Number\.isFinite\(rawCount\)/);
const planner=source("app/api/journeys/route.ts");
assert.match(planner,/validBody\(body\)/);
assert.match(planner,/AbortSignal\.timeout\(23_000\)/);
const walking=source("app/api/walk/route.ts");
assert.match(walking,/body\?\.from/);
assert.match(walking,/AbortSignal\.any/);
const inspector=source("app/live-trip-inspector.tsx");
assert.match(inspector,/Retain the last itinerary/);
assert.match(inspector,/realtime=\{sourceCurrent&&trip\.realTime\}/);
assert.match(inspector,/detailState!=="loading"&&stops\.length>0&&<ol/);
const listing=source("app/live-board.tsx");
assert.match(listing,/delay!==0/,"Pünktlich filter must not contain +1 to +4 minutes");
assert.match(listing,/Alle Fahrten anzeigen/);
const update=source("app/pwa-register.tsx");
assert.match(update,/Storage can be blocked in private browsing/);
const css=source("app/styles/v56-experience.css");
assert.match(css,/@media \(max-width: 350px\)/);
assert.match(css,/@media \(forced-colors: active\)/);
assert.match(css,/@media \(prefers-reduced-motion: reduce\)/);
console.log("V56 regression audit: freshness, arrival confidence, inputs, recovery and responsive UX passed");
