import assert from "node:assert/strict";
import {commuterDepartureTime} from "../app/commuter-departure.ts";
import {readFileSync} from "node:fs";
const read=(p)=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const result=commuterDepartureTime(Date.parse("2026-10-23T07:01:01Z"));
assert.deepEqual(result,{local:"2026-10-23T09:10",iso:"2026-10-23T07:10:00.000Z"});
const spring=commuterDepartureTime(Date.parse("2026-03-29T00:55:00Z"));
assert.equal(spring.local,"2026-03-29T03:00","DST spring transition must not invent a nonexistent local minute");
assert.equal(spring.iso,"2026-03-29T01:00:00.000Z");
const autumn=commuterDepartureTime(Date.parse("2026-10-25T00:55:00Z"));
assert.equal(autumn.local,"2026-10-25T02:00");
assert.equal(autumn.iso,"2026-10-25T01:00:00.000Z","Autumn duplicate 02:00 must keep real UTC instant");
assert.equal(commuterDepartureTime(Date.parse("2026-10-23T07:00:00Z")).local,"2026-10-23T09:05");
const page=read("app/page.tsx"),saved=read("app/saved-routes-panel.tsx");
assert.match(page,/function openSavedRoute\(route:SavedRoute,reverse:boolean,searchNow=false\)/);
assert.match(page,/runPlanner\(\{start:from,target:to,departureIso:next.iso\}\)/,"Direct search needs explicit route identity, not stale asynchronous React state");
assert.match(page,/setArriveBy\(false\)/);
assert.match(page,/departure:override\?\.departureIso\?\?berlinLocalToIso\(journeyDeparture\)/);
assert.match(saved,/onOpen\(route,false,true\)/);
assert.match(saved,/>Jetzt prüfen</);
console.log("V62 commuter: safe one-tap search, explicit route identity, DST and realtime query start passed.");
