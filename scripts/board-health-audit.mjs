import assert from "node:assert/strict";
import {assessBoardHealth,stationCondition} from "../app/board-health.ts";
const now=Date.parse("2026-10-14T09:00:00Z");
const fresh={total:24,realtime:8,updatedAt:new Date(now-15_000).toISOString(),realtimeStatus:"live"};
const good=assessBoardHealth(fresh,now);
assert.equal(good.state,"live");
assert.deepEqual([good.realtimeCount,good.totalCount,good.percentage],[8,24,33]);
assert.equal(good.sourceTime,new Date(now-15_000).toISOString());
assert.equal(assessBoardHealth({...fresh,updatedAt:new Date(now-180_001).toISOString()},now).state,"stale");
assert.equal(assessBoardHealth({...fresh,realtimeStatus:"stale"},now).state,"stale");
assert.equal(assessBoardHealth({...fresh,realtime:0,realtimeStatus:"schedule"},now).state,"schedule");
assert.equal(assessBoardHealth({...fresh,realtime:0,realtimeStatus:"live"},now).state,"schedule");
assert.equal(assessBoardHealth({...fresh,realtime:500},now).realtimeCount,24,"Impossible provider counters are bounded");
assert.equal(assessBoardHealth({...fresh,updatedAt:"invalid"},now).state,"unknown");
assert.equal(assessBoardHealth({...fresh,updatedAt:new Date(now+61_000).toISOString()},now).state,"unknown");
assert.equal(assessBoardHealth({...fresh,total:0},now).state,"unknown");
assert.equal(assessBoardHealth(null,now).state,"unknown");
assert.equal(assessBoardHealth({...fresh,warnings:["No data", "", "Partial"]},now).warningCount,2);
const condition={...fresh,stationId:"berlin",canceled:0,delayed6:0,delayed15:0,delaySamples:8};
assert.deepEqual(stationCondition(condition,"berlin",now),{tone:"good",label:"stabil"});
assert.deepEqual(stationCondition({...condition,delayed15:2},"berlin",now),{tone:"risk",label:"angespannt"});
assert.deepEqual(stationCondition({...condition,delayed6:3},"berlin",now),{tone:"medium",label:"beobachten"});
assert.equal(stationCondition({...condition,delaySamples:1},"berlin",now).tone,"unknown","One delay sample is insufficient for a green claim.");
assert.equal(stationCondition({...condition,updatedAt:new Date(now-500_000).toISOString()},"berlin",now).tone,"unknown");
assert.equal(stationCondition({...condition,stationId:"hamburg"},"berlin",now).label,"lädt","Never show a different station's status.");
console.log("Station board health audit passed");
